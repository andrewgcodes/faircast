def build_game_prompts(fmt, name, n_train, n_eval, seed):
    import random
    names = list(GAMES) if name == "mix" else None; gen = None if names else GAMES[name][0]
    def make(rng, n):
        out = []
        for i in range(n):
            g = GAMES[names[i % len(names)]][0] if names else gen
            q, gold = g(rng); out.append((fmt(q), gold))
        return out
    return make(random.Random(1000 + seed), n_train), make(random.Random(7), n_eval)

def reward_fn(text, gold):
    if isinstance(gold, dict):
        k = gold["kind"]
        if k == "countdown": return _reward_countdown(text, gold)
        if k == "rg": return _reward_rg(text, gold)
        if k == "game": return _reward_game(text, gold)
        if k == "mbpp_plus": return _reward_mbpp_plus(text, gold)
        return _reward_mbpp(text, gold)
    pred = last_boxed(text)
    if pred is None: return 0.0
    p = pred.replace(",", "").replace("$", "").replace(" ", "").strip(); g = gold.replace(",", "").replace("$", "").replace(" ", "").strip()
    try:
        return float(abs(float(p) - float(g)) < 1e-6)
    except Exception:
        pass
    try:
        from math_verify import parse, verify
        return float(verify(parse("$" + gold + "$"), parse("$" + pred + "$")))
    except Exception:
        return float(p == g)

