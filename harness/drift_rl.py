def _reward_countdown(text, gold):
    import re as _re
    pred = last_boxed(text)
    if pred is None: return 0.0
    expr = pred.replace("\\times", "*").replace("\\cdot", "*").replace("\\div", "/").replace("×", "*").replace("÷", "/").replace("$", "").strip()
    if not _re.fullmatch(r"[0-9+\-*/(). ]+", expr): return 0.0
    used = sorted(int(x) for x in _re.findall(r"\d+", expr))
    if used != sorted(gold["nums"]): return 0.0
    try:
        return float(abs(eval(expr, {"__builtins__": {}}, {}) - gold["target"]) < 1e-9)
    except Exception:
        return 0.0

