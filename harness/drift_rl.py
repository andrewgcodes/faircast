def sr_round(x):
    """Stochastic rounding fp32 -> bf16: round down w.p. 1-p, up w.p. p, p = fractional position between the two bf16 neighbours."""
    import torch
    lo = x.to(torch.bfloat16); lo_f = lo.float()
    bits = lo.view(torch.int16)
    # neighbour away from lo in the direction of x: increment magnitude bits if |x|>|lo|, else decrement
    away = (x.abs() > lo_f.abs())
    nb = torch.where(away, bits + 1, bits - 1).view(torch.bfloat16)
    nb = torch.where(lo_f == 0, torch.where(x > 0, torch.tensor(1, dtype=torch.int16, device=x.device), torch.tensor(-32767, dtype=torch.int16, device=x.device)).view(torch.bfloat16).expand_as(lo), nb)
    hi_f = nb.float(); gap = hi_f - lo_f
    prob = torch.where(gap != 0, (x - lo_f) / gap, torch.zeros_like(x)).clamp(0, 1)
    return torch.where(torch.rand_like(x) < prob, nb, lo)

class Muon:
    """Minimal Muon: momentum -> Newton-Schulz orthogonalisation -> RMS-matched update (0.2*sqrt(max(m,n))) ; AdamW side-optimizer."""
    def __init__(self, params, lr, momentum, weight_decay, adam_params, adam_lr, adam_wd):
        import torch
        self.params = list(params); self.lr = lr; self.mom = momentum; self.wd = weight_decay
        self.buf = [torch.zeros_like(p) for p in self.params]
        self.adam = torch.optim.AdamW(adam_params, lr=adam_lr, betas=(0.9, 0.999), weight_decay=adam_wd, eps=1e-8)
        self.param_groups = self.adam.param_groups; self.state = self.adam.state; self.last_update_sq = 0.0; self.last_update_max = 0.0
    @staticmethod
    def ns(G, steps=5):
        import torch
        a, b, c = (3.4445, -4.7750, 2.0315)
        X = G.bfloat16(); X = X / (X.norm() + 1e-7)
        if G.size(0) > G.size(1): X = X.T
        for _ in range(steps):
            A = X @ X.T; B = b * A + c * A @ A; X = a * X + B @ X
        if G.size(0) > G.size(1): X = X.T
        return X.float()
    def zero_grad(self, set_to_none=True):
        for p in self.params: p.grad = None
        self.adam.zero_grad(set_to_none=set_to_none)
    def state_dict(self):
        return dict(adam=self.adam.state_dict(), buf=[b.detach().cpu() for b in self.buf], lr=self.lr)
    def load_state_dict(self, sd):
        self.adam.load_state_dict(sd["adam"])
        for b, v in zip(self.buf, sd["buf"]): b.copy_(v.to(b.device))
    def step(self):
        import torch, math
        sq = 0.0; mx = 0.0
        with torch.no_grad():
            for p, b in zip(self.params, self.buf):
                if p.grad is None: continue
                b.mul_(self.mom).add_(p.grad)
                g = p.grad.add(b, alpha=self.mom)  # nesterov
                u = self.ns(g) * (0.2 * math.sqrt(max(p.shape)))
                upd = self.lr * (u + self.wd * p)
                p.sub_(upd); sq += upd.pow(2).sum().item(); mx = max(mx, upd.abs().max().item())
        self.adam.step(); self.last_update_sq = sq; self.last_update_max = mx

SYSTEM = "Solve the problem. Reason briefly, then give the final answer as \\boxed{...}."

def last_boxed(s):
    i = s.rfind("\\boxed")
    if i < 0: return None
    j = s.find("{", i); depth = 0
    for k in range(j, len(s)):
        if s[k] == "{": depth += 1
        elif s[k] == "}":
            depth -= 1
            if depth == 0: return s[j + 1:k]
    return None

